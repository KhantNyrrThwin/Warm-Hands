def top_hospital_entries(entries: list[dict], k: int = 100) -> list[dict]:
    hospital = [item for item in entries if item["gloss"] in HOSPITAL_GLOSSES]
    hospital.sort(key=lambda item: (-len(item.get("instances", [])), item["gloss"]))
    return hospital[:k]
